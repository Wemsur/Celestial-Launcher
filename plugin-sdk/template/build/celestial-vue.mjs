/**
 * Point a plugin's `vue` imports at the launcher's Vue.
 *
 * A plugin is loaded as a standalone module from a blob/asset URL, so a bare
 * `import ... from 'vue'` has nothing to resolve against at runtime, and
 * bundling a second copy of Vue would give it a different runtime whose vnodes
 * the launcher cannot render.
 *
 * This writes a real shim module and hands back a `resolve.alias` entry for it.
 * Generating an actual file (rather than resolving to a virtual module id) is
 * deliberate: aliasing is resolved deterministically by Vite, whereas a
 * virtual-module plugin hook depends on hook ordering that is easy to get
 * subtly wrong — and when it goes wrong the failure mode is a bare `vue` import
 * surviving into the bundle, which only shows up once the launcher loads the
 * plugin.
 *
 * The shim's named exports are read from the installed `vue`, so single-file
 * components — whose compiled output imports a wide set of runtime helpers —
 * resolve every symbol against the launcher's instance.
 */

import { mkdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join } from 'node:path'

const GLOBAL_KEY = '__CELESTIAL_PLUGIN_VUE__'

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/

/**
 * @param {string} projectRoot absolute path to the plugin project
 */
export function celestialVueAlias(projectRoot) {
	const generatedDir = join(projectRoot, 'build', '.generated')
	const shimPath = join(generatedDir, 'vue-shim.js')

	let vue
	try {
		// Resolved from the project root so it finds the plugin's own `vue`
		// devDependency rather than whatever the host process has loaded.
		vue = createRequire(join(projectRoot, 'package.json'))('vue')
	} catch (error) {
		throw new Error(
			[
				'Could not load `vue` to build the plugin Vue shim.',
				'Run `pnpm install --ignore-workspace` in the plugin folder first.',
				`(${error instanceof Error ? error.message : String(error)})`,
			].join(' '),
		)
	}

	const names = Object.keys(vue)
		.filter((name) => name !== 'default' && IDENTIFIER.test(name))
		.sort()

	const shim = [
		'// GENERATED by build/celestial-vue.mjs — do not edit, do not commit.',
		`const runtime = globalThis[${JSON.stringify(GLOBAL_KEY)}]`,
		'if (!runtime) {',
		'	throw new Error(',
		"		'Celestial: the launcher did not expose its Vue. This plugin must run inside Celestial Launcher.',",
		'	)',
		'}',
		'export default runtime',
		...names.map(
			(name) => `export const ${name} = runtime[${JSON.stringify(name)}]`,
		),
		'',
	].join('\n')

	mkdirSync(generatedDir, { recursive: true })
	writeFileSync(shimPath, shim, 'utf8')

	// Only bare `vue` is redirected; `vue-router` and friends would need their
	// own shim if a plugin is ever given them.
	return { find: /^vue$/, replacement: shimPath }
}
